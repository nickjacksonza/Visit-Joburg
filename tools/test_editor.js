// node tools/test_editor.js : checks the events editor rules and that the shipped JSON round-trips unchanged.
const assert = require("assert"), fs = require("fs"), path = require("path");
const L = require("../editor/editor-lib.js");
const file = path.join(__dirname, "..", "content", "events.json");
const raw = fs.readFileSync(file, "utf8"), data = JSON.parse(raw);
assert.strictEqual(L.dump(L.clean(data)), raw, "dump(clean(file)) must equal the file, so saves don't reformat it");
const bad = (f) => assert.throws(f, Error);
const ev = (o) => Object.assign({ name: "X", description: "D", start: "2027-01-01T10:00", end: "2027-01-01T12:00", place: "P", street: "S", url: "https://example.com/x", price: 0, published: true }, o);
const wrap = (...e) => ({ timezone: "+02:00", currency: "ZAR", events: e });
bad(() => L.clean(wrap(ev({ name: "<b>" }))));
bad(() => L.clean(wrap(ev({ name: "" }))));
bad(() => L.clean(wrap(ev({ description: "" }))));
bad(() => L.clean(wrap(ev({ price: 1.234 }))));
bad(() => L.clean(wrap(ev({ price: -1 }))));
bad(() => L.clean(wrap(ev({ start: "2027-02-30T10:00", end: "2027-03-01T10:00" }))));
bad(() => L.clean(wrap(ev({ start: "5 Dec" }))));
bad(() => L.clean(wrap(ev({ end: "2027-01-01T09:00" }))));
bad(() => L.clean(wrap(ev({ url: "javascript:alert(1)" }))));
bad(() => L.clean(wrap(ev({ url: "http://example.com" }))));
bad(() => L.clean(wrap(ev({ published: "yes" }))));
bad(() => L.clean(wrap(ev({ id: "x" }), ev({ id: "x" }))));
const c = L.clean(wrap(ev({ name: "  Late   Show ", start: "2027-05-01T20:00", end: "2027-05-01T22:00" }), ev({ name: "Early" })));
assert.deepStrictEqual(c.events.map((e) => e.id), ["early", "late-show"], "events are sorted by start and get ids from their names");
assert.strictEqual(L.ended(ev({ end: "2027-01-01T12:00" }), "+02:00", new Date("2027-01-01T10:30:00Z")), true);
assert.strictEqual(L.ended(ev({ end: "2027-01-01T12:00" }), "+02:00", new Date("2027-01-01T09:30:00Z")), false);
assert.deepStrictEqual(L.summary(data, L.clean(wrap(ev({ id: "new", name: "New" })))).slice(0, 1), ["Added New"]);
console.log("editor tests passed");
